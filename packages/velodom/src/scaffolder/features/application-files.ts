/** Writes the router example. */
async function writeRouterExample(plan: ScaffoldPlan) {
  const extension = sourceExtension(plan);
  await writeText(join(plan.destination, "src/pages/about/index.html"), `<main class="shell hero">
  <p>VeloDom route</p>
  <h1>About this project</h1>
  <p>This route was discovered from its folder. No route table was required.</p>
</main>
`);
  await writeText(join(plan.destination, `src/pages/about/config.${extension}`), `export default {
  path: "/about",
  seo: {
    title: "About",
    description: "A folder-discovered VeloDom route.",
  },
};
`);
  await writeHomeConfig(plan, true);
  await writeNavigation(plan);
}

/** Writes the home config. */
async function writeHomeConfig(plan: ScaffoldPlan, withLayout: boolean) {
  const extension = sourceExtension(plan);
  await writeText(join(plan.destination, `src/pages/home/config.${extension}`), `export default {
  path: "/",
  ${withLayout ? 'layout: "default",\n  ' : ""}seo: {
    title: "${plan.starter === "blog" ? "VeloDom Blog" : "VeloDom Starter"}",
    description: "An editable ${plan.starter} application generated by VeloDom.",
  },
};
`);
}

/** Writes the navigation. */
async function writeNavigation(plan: ScaffoldPlan) {
  const links = [
    '<a href="/" vd-nav>Home</a>',
    ...(plan.starter === "blog" ? ['<a href="/posts" vd-nav>Posts</a>'] : []),
    '<a href="/about" vd-nav>About</a>',
    ...(plan.i18n ? ['<a href="/localization" vd-nav>Languages</a>'] : [])
  ];

  await writeText(join(plan.destination, "src/components/site-nav/index.html"), `<nav class="site-nav shell" aria-label="Primary navigation">
  <a class="brand" href="/" vd-nav>VeloDom</a>
  ${links.join("\n  ")}
</nav>
`);
  await writeText(join(plan.destination, "src/layouts/default/index.html"), `<vd-component name="site-nav"></vd-component>
<vd-page></vd-page>
`);
}

/** Writes the localization example. */
async function writeLocalizationExample(plan: ScaffoldPlan) {
  await writeGeneratedFiles(
    plan.destination,
    createLocalizationFeatureFiles(plan.language)
  );

  if (plan.router) await writeNavigation(plan);
}

/** Writes the tests. */
async function writeTests(plan: ScaffoldPlan) {
  if (plan.testing === "none") return;

  await writeGeneratedFiles(
    plan.destination,
    createTestingFeatureFiles(
      plan.language,
      plan.testing,
      plan.packageManager === "pnpm" || plan.packageManager === "yarn"
        ? `${plan.packageManager} dev`
        : `${plan.packageManager} run dev`
    )
  );
}

/** Writes a deterministic map of generated application files. */
async function writeGeneratedFiles(
  destination: string,
  files: Record<string, string>
) {
  await Promise.all(Object.entries(files).map(([file, source]) => (
    writeText(join(destination, file), source)
  )));
}

/** Converts the source to type script. */
async function convertSourceToTypeScript(directory: string) {
  const entries = await readdir(directory, { withFileTypes: true });

  for (const entry of entries) {
    const path = join(directory, entry.name);

    if (entry.isDirectory()) {
      await convertSourceToTypeScript(path);
      continue;
    }

    if (extname(entry.name) === ".js") {
      await rename(path, path.slice(0, -3) + ".ts");
    }
  }
}

/** Performs the internal `sourceExtension()` operation. */
function sourceExtension(plan: ScaffoldPlan) {
  return plan.language === "typescript" ? "ts" : "js";
}

/** Writes the text. */
async function writeText(file: string, source: string) {
  await mkdir(dirname(file), { recursive: true });
  await writeFile(file, source);
}
