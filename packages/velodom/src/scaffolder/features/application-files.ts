/**
 * ----------------------------------------
 * Module: Scaffolder Application Features
 * ----------------------------------------
 *
 * Installs optional application-owned examples for routing, localization,
 * testing, and styling after a starter has been copied.
 * ----------------------------------------
 */

import { mkdir, rename, readdir, writeFile } from "node:fs/promises";
import { dirname, extname, join } from "node:path";
import type { ScaffoldPlan } from "../types.ts";
import {
  createLocalizationFeatureFiles,
  createTestingFeatureFiles
} from "./optional-files.ts";

/** Applies language conversion and optional feature files to one starter. */
export async function installApplicationFeatures(plan: ScaffoldPlan) {
  if (plan.language === "typescript") {
    await convertSourceToTypeScript(join(plan.destination, "src"));
  }

  await writeMainEntry(plan);
  await writeGlobalStyles(plan);

  if (plan.router) await writeRouterExample(plan);
  if (plan.i18n) await writeLocalizationExample(plan);
  if (plan.testing !== "none") await writeTests(plan);
}

/** Writes the main entry. */
async function writeMainEntry(plan: ScaffoldPlan) {
  const extension = sourceExtension(plan);
  await writeText(join(plan.destination, `src/main.${extension}`), `import { mountVeloDom } from "velodom/vite";
import "./style.css";

await mountVeloDom();
`);
}

